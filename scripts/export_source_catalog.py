#!/usr/bin/env python3
"""Render the shared Python source catalog into the desktop artifacts.

The desktop must not hand-copy source, route, alias, or env-name lists. This
script writes the same catalog twice: JSON for the Rust build (``include_str!``)
and an ES module for the webview tests. Run it after changing Python source
metadata::

    python scripts/export_source_catalog.py

``--check`` exits non-zero when the checked-in artifacts are stale; the Python
regression suite and CI use the same comparison.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from multi_search_mcp.src.search.catalog import build_source_catalog  # noqa: E402

JSON_PATH = ROOT / "desktop" / "source-catalog.json"
JS_PATH = ROOT / "desktop" / "ui" / "source-catalog.js"
JS_HEADER = (
    "// Generated by scripts/export_source_catalog.py from "
    "multi_search_mcp/src/search/catalog.py. Do not edit by hand.\n"
)


def render_json(catalog: dict[str, Any]) -> str:
    return json.dumps(catalog, ensure_ascii=False, indent=2, sort_keys=True) + "\n"


def render_js(catalog: dict[str, Any]) -> str:
    body = json.dumps(catalog, ensure_ascii=False, indent=2, sort_keys=True)
    return f"{JS_HEADER}export const SOURCE_CATALOG = {body};\n"


def artifacts(catalog: dict[str, Any] | None = None) -> dict[Path, str]:
    catalog = build_source_catalog() if catalog is None else catalog
    return {JSON_PATH: render_json(catalog), JS_PATH: render_js(catalog)}


def check(paths: dict[Path, str] | None = None) -> list[Path]:
    """Return the stale artifact paths (empty when everything is current)."""
    stale = []
    for path, expected in (paths or artifacts()).items():
        try:
            actual = path.read_text(encoding="utf-8")
        except FileNotFoundError:
            stale.append(path)
            continue
        if actual != expected:
            stale.append(path)
    return stale


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the checked-in artifacts instead of writing them",
    )
    args = parser.parse_args(argv)

    rendered = artifacts()
    if args.check:
        stale = check(rendered)
        if stale:
            for path in stale:
                print(f"stale source catalog artifact: {path.relative_to(ROOT)}", file=sys.stderr)
            print("run: python scripts/export_source_catalog.py", file=sys.stderr)
            return 1
        return 0

    for path, text in rendered.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
