//! SQLite credential storage with current-user DPAPI encryption. Shared Python protocol v1.
use rusqlite::OptionalExtension;
use serde::Serialize;
use serde_json::Value;

pub(crate) const MAX_KEY_LENGTH: usize = 1024;

/// Stable reason string shared by the status payloads (`CredentialOverview`,
/// `MigrationPlan`) and the typed unsupported error. One definition, so the
/// wire value cannot drift between consumers.
pub(crate) const PLATFORM_UNSUPPORTED_REASON: &str = "platform_unsupported";
/// Stable IPC code for a rejected encrypted operation on this platform.
pub(crate) const PLATFORM_UNSUPPORTED_CODE: &str = "credential_platform_unsupported";
/// User-facing text for the same rejection. Used only as the human message.
const PLATFORM_UNSUPPORTED_MESSAGE: &str =
    "加密凭据存储仅支持 Windows 当前用户 DPAPI；当前平台不可用，没有明文回退，已保存内容未改动。";
/// Credential store primary keys, derived from the generated source catalog
/// (`credential_store_providers`). The hand-written list this replaced drifted
/// from Core; the artifact is regenerated by `scripts/export_source_catalog.py`.
pub(crate) fn store_providers() -> &'static [String] {
    &crate::source_catalog::catalog().credential_store_providers
}

#[cfg_attr(not(feature = "test-fixtures"), allow(dead_code))]
/// Whether `provider` is a key this store may address. Cookie custody has its
/// own provider key and validates a cookie map, so it is not a key provider.
pub(crate) fn is_store_provider(provider: &str) -> bool {
    store_providers().iter().any(|known| known == provider)
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) enum CredentialError {
    Unavailable(String),
    /// Encrypted storage cannot run on this platform (DPAPI is Windows-only).
    /// Typed, so callers map it to `PLATFORM_UNSUPPORTED_CODE` without matching text.
    PlatformUnsupported,
    Unreadable,
    /// Only DPAPI (Windows) can tell a corrupt blob from an unavailable store.
    #[cfg_attr(not(windows), allow(dead_code))]
    DecryptionFailed(u32),
    Invalid(&'static str),
}
impl std::fmt::Display for CredentialError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Unavailable(message) => f.write_str(message),
            Self::PlatformUnsupported => f.write_str(PLATFORM_UNSUPPORTED_MESSAGE),
            Self::Unreadable => f.write_str("已保存的凭据无法读取"),
            Self::DecryptionFailed(code) => write!(f, "DPAPI decryption failed (Windows error {code})"),
            Self::Invalid(message) => f.write_str(message),
        }
    }
}
/// Plain JSON backend boundary; native implementation encrypts before writing and decrypts on read.
/// Test memory implementations never access real user data.
pub(crate) trait CredentialBackend: Send + Sync {
    fn read(&self, provider: &str) -> Result<Option<Vec<u8>>, CredentialError>;
    fn write(&self, provider: &str, blob: &[u8]) -> Result<(), CredentialError>;
    fn delete(&self, provider: &str) -> Result<bool, CredentialError>;
    fn save_jina(&self, value: Value, saved_at: f64) -> Result<(), CredentialError> {
        let _ = (value, saved_at);
        Err(CredentialError::Unavailable("atomic Jina save is not supported by this backend".into()))
    }
    /// Per-row append against the CURRENT stored value.
    fn append(&self, provider: &str, keys: &[String], saved_at: f64) -> Result<(), CredentialError> {
        // Row mutations must be atomic: only backends that can run a real
        // read-modify-write unit (SQLite's IMMEDIATE transaction) override
        // this. Anything else fails explicitly rather than taking a lossy
        // separate read/write path that could drop concurrent writes.
        let _ = (provider, keys, saved_at);
        Err(CredentialError::Unavailable(
            "per-row credential append is not supported by this backend".into(),
        ))
    }
    /// Per-row removal guarded by the exact editor snapshot.
    fn remove_row(&self, provider: &str, index: usize, expected: &str, saved_at: f64) -> Result<(), CredentialError> {
        // Same atomicity rule as `append`: no non-transactional fallback.
        let _ = (provider, index, expected, saved_at);
        Err(CredentialError::Unavailable(
            "per-row credential removal is not supported by this backend".into(),
        ))
    }
}
pub(crate) fn validate_key(key: &str) -> Result<String, CredentialError> {
    let text = key.trim();
    if text.is_empty()
        || text.len() > MAX_KEY_LENGTH
        || text.chars().any(|c| (c as u32) < 32 || c as u32 == 127)
    {
        return Err(CredentialError::Invalid(
            "key must be 1-1024 characters with no control characters",
        ));
    }
    Ok(text.to_string())
}
// Namespace no longer controls normal storage; provider is the database primary key.
pub(crate) fn namespace(_: &std::collections::BTreeMap<String, String>) -> String {
    String::new()
}
pub(crate) fn target(_: &str, provider: &str) -> String {
    provider.to_string()
}
fn validate_value(provider: &str, value: &Value) -> bool {
    if provider == crate::cookie::PROVIDER { return crate::cookie::valid(value); }
    match value {
        Value::String(s) => validate_key(s).is_ok(),
        Value::Array(items) => !items.is_empty() && items.iter().all(|v| (v.is_string() || provider == "jina" && v.is_object()) && validate_value(provider,v)),
        Value::Object(map) if provider == "jina" => map.get("key").and_then(Value::as_str).is_some_and(|s| validate_key(s).is_ok()) && map.get("exhausted").is_none_or(Value::is_boolean),
        _ => false,
    }
}
fn editor_value(text: &str) -> Result<Value, CredentialError> {
    let keys: Vec<String> = text.lines().map(validate_key).collect::<Result<_, _>>()?;
    if keys.is_empty() || keys.len() > 256 {
        return Err(CredentialError::Invalid("provide 1-256 keys, one per line"));
    }
    Ok(if keys.len() == 1 {
        Value::String(keys[0].clone())
    } else {
        serde_json::json!(keys)
    })
}
pub(crate) fn snapshot(text: &str) -> String {
    use sha2::{Digest, Sha256};
    format!("{:x}", Sha256::digest(text.as_bytes()))
}
pub(crate) fn encode_blob(key: &Value, saved_at: f64) -> Vec<u8> {
    serde_json::json!({"v":1,"key":key,"saved_at":saved_at})
        .to_string()
        .into_bytes()
}
pub(crate) fn decode_blob(provider: &str, blob: &[u8]) -> Result<(Value, f64), CredentialError> {
    let data: Value = serde_json::from_slice(blob).map_err(|_| CredentialError::Unreadable)?;
    let key = data.get("key").ok_or(CredentialError::Unreadable)?.clone();
    let valid = validate_value(provider, &key);
    let saved_at = data
        .get("saved_at")
        .and_then(Value::as_f64)
        .filter(|v| v.is_finite())
        .ok_or(CredentialError::Unreadable)?;
    if data.get("v").and_then(Value::as_i64) != Some(1) || !valid {
        return Err(CredentialError::Unreadable);
    }
    Ok((key, saved_at))
}
pub(crate) fn load(
    backend: &dyn CredentialBackend,
    namespace: &str,
    provider: &str,
) -> Result<Option<(Value, f64)>, CredentialError> {
    backend
        .read(&target(namespace, provider))?
        .map(|blob| decode_blob(provider, &blob))
        .transpose()
}
/// Jina editor semantics: the editor shows one key per line. A line whose key
/// matches a stored structured entry keeps that entry verbatim (including
/// `exhausted` and any extra metadata); a new/changed line is saved as a plain
/// key string; a removed line drops its entry. Other providers are unaffected.
pub(crate) fn merge_jina_metadata(edited: Value, previous: Option<&Value>) -> Value {
    let Some(previous) = previous else { return edited };
    let mut stored: Vec<&Value> = match previous {
        Value::Array(items) => items.iter().collect(),
        _ => vec![previous],
    };
    let lines: Vec<String> = match &edited {
        Value::String(s) => vec![s.clone()],
        Value::Array(items) => items.iter().filter_map(Value::as_str).map(str::to_string).collect(),
        _ => Vec::new(),
    };
    if lines.is_empty() {
        return edited;
    }
    let merged: Vec<Value> = lines
        .into_iter()
        .map(|line| {
            match stored.iter().position(|item| {
                // The editor trims input; compare the same normalized key without
                // rewriting the original entry or its metadata.
                item.as_str()
                    .or_else(|| item.get("key").and_then(Value::as_str))
                    .map(str::trim) == Some(line.as_str())
            }) {
                // Consume matches in stored order, preserving duplicate entries independently.
                Some(index) => stored.remove(index).clone(),
                None => Value::String(line),
            }
        })
        .collect();
    if merged.len() == 1 {
        merged.into_iter().next().unwrap()
    } else {
        Value::Array(merged)
    }
}
pub(crate) fn save(
    backend: &dyn CredentialBackend,
    namespace: &str,
    provider: &str,
    key: &str,
    saved_at: f64,
) -> Result<f64, CredentialError> {
    let value = editor_value(key)?;
    if provider == "jina" { backend.save_jina(value, saved_at)?; }
    else { backend.write(&target(namespace, provider), &encode_blob(&value, saved_at))?; }
    Ok(saved_at)
}
pub(crate) fn remove(
    backend: &dyn CredentialBackend,
    namespace: &str,
    provider: &str,
) -> Result<bool, CredentialError> {
    backend.delete(&target(namespace, provider))
}

/// Flatten a stored `key` value into row entries. Strings and Jina objects are
/// kept verbatim (objects preserve every metadata field); anything else is an
/// unreadable shape for row operations.
fn stored_rows(provider: &str, key: &Value) -> Result<Vec<Value>, CredentialError> {
    let items: &[Value] = match key {
        Value::Array(items) => items,
        other => std::slice::from_ref(other),
    };
    if !validate_value(provider, key) {
        return Err(CredentialError::Unreadable);
    }
    Ok(items.to_vec())
}
fn collapse_rows(rows: Vec<Value>) -> Value {
    if rows.len() == 1 {
        rows.into_iter().next().unwrap()
    } else {
        Value::Array(rows)
    }
}
/// Editor line for one row. `credential_read` renders every valid entry
/// (string or Jina object `key`), so any entry without a line is a shape the
/// row operations cannot address: reject instead of silently hiding it.
fn row_editor_line(value: &Value) -> Result<String, CredentialError> {
    value
        .as_str()
        .or_else(|| value.get("key").and_then(Value::as_str))
        .map(str::to_string)
        .ok_or(CredentialError::Unreadable)
}
/// Rows after appending `new_keys` to an already-decoded stored value.
fn append_rows(provider: &str, stored: Option<&Value>, keys: &[String]) -> Result<Value, CredentialError> {
    if keys.is_empty() || keys.len() > 256 {
        return Err(CredentialError::Invalid("provide 1-256 keys"));
    }
    let mut new_keys: Vec<String> = Vec::with_capacity(keys.len());
    for key in keys {
        new_keys.push(validate_key(key)?);
    }
    let mut rows = match stored {
        Some(key) => stored_rows(provider, key)?,
        None => Vec::new(),
    };
    for row in &rows {
        row_editor_line(row)?;
    }
    if rows.len() + new_keys.len() > 256 {
        return Err(CredentialError::Invalid("credential rows cannot exceed 256"));
    }
    rows.extend(new_keys.into_iter().map(Value::String));
    Ok(collapse_rows(rows))
}
/// Rows after removing stored entry `index` (the editor row number, so
/// duplicates keep their identity and remove the exact occurrence). `expected`
/// is the exact `credential_read.value` snapshot the UI saw; a mismatch means
/// the caller is working from stale rows and nothing is written. `None` means
/// the last row was removed and the credentials row must be deleted.
fn remove_row_at(provider: &str, stored: &Value, index: usize, expected: &str) -> Result<Option<Value>, CredentialError> {
    let mut rows = stored_rows(provider, stored)?;
    let snapshot = rows
        .iter()
        .map(row_editor_line)
        .collect::<Result<Vec<_>, _>>()?
        .join("\n");
    if self::snapshot(&snapshot) != expected {
        return Err(CredentialError::Invalid("credential rows changed; refresh and retry"));
    }
    if index >= rows.len() {
        return Err(CredentialError::Invalid("credential row index out of range"));
    }
    rows.remove(index);
    Ok(if rows.is_empty() { None } else { Some(collapse_rows(rows)) })
}
/// Append validated keys to the CURRENT stored rows for `provider`. Existing
/// scalar/object rows are preserved verbatim; no whole-list replacement and
/// no Jina metadata reconstruction. Never falls back to whole-editor `save`.
pub(crate) fn append_keys(
    backend: &dyn CredentialBackend,
    namespace: &str,
    provider: &str,
    keys: &[String],
    saved_at: f64,
) -> Result<f64, CredentialError> {
    backend.append(&target(namespace, provider), keys, saved_at)?;
    Ok(saved_at)
}
/// Remove one editor row for `provider` (generic backend path), guarded by
/// the exact `credential_read.value` snapshot.
pub(crate) fn remove_at(
    backend: &dyn CredentialBackend,
    namespace: &str,
    provider: &str,
    index: usize,
    expected: &str,
    saved_at: f64,
) -> Result<(), CredentialError> {
    backend.remove_row(&target(namespace, provider), index, expected, saved_at)
}

#[cfg_attr(not(feature = "native-window"), allow(dead_code))]
pub(crate) struct SqliteCredentialBackend {
    pub path: std::path::PathBuf,
}
impl SqliteCredentialBackend {
    fn connection(&self) -> Result<rusqlite::Connection, CredentialError> {
        if self.path.as_os_str().is_empty() {
            return Err(CredentialError::Unavailable("无法定位配置数据库".into()));
        }
        crate::config_db::open(&self.path).map_err(CredentialError::Unavailable)
    }
    /// One `IMMEDIATE` transaction per row mutation: decrypt + read rows,
    /// apply `change`, encrypt, then write or delete before commit. Holding
    /// the write lock across the whole read-modify-write window keeps two
    /// concurrent appends (or append racing remove) from losing rows. Any
    /// error before commit drops the transaction, which rolls back.
    fn mutate_rows(
        &self,
        provider: &str,
        saved_at: f64,
        change: impl FnOnce(Option<&Value>) -> Result<Option<Value>, CredentialError>,
    ) -> Result<(), CredentialError> {
        // Capability first: a rejected write must not open the database at all.
        require_storage()?;
        let mut connection = self.connection()?;
        let transaction = connection
            .transaction_with_behavior(rusqlite::TransactionBehavior::Immediate)
            .map_err(|_| CredentialError::Unavailable("配置数据库事务失败".into()))?;
        let encrypted: Option<Vec<u8>> = transaction
            .query_row(
                "SELECT encrypted_value FROM credentials WHERE provider=?1",
                [provider],
                |r| r.get(0),
            )
            .optional()
            .map_err(|_| CredentialError::Unavailable("无法读取配置数据库凭据".into()))?;
        let stored = encrypted.map(|blob| crypt(&blob, false)).transpose()?;
        let decoded = stored.map(|blob| decode_blob(provider, &blob)).transpose()?;
        match change(decoded.map(|(key, _)| key).as_ref())? {
            None => {
                transaction
                    .execute("DELETE FROM credentials WHERE provider=?1", [provider])
                    .map_err(|_| CredentialError::Unavailable("删除凭据失败".into()))?;
            }
            Some(key) => {
                let blob = encode_blob(&key, saved_at);
                let (_, saved) = decode_blob(provider, &blob)?;
                let encrypted = crypt(&blob, true)?; // Encrypt before touching the row.
                transaction.execute("INSERT INTO credentials(provider,encrypted_value,saved_at) VALUES(?1,?2,?3) ON CONFLICT(provider) DO UPDATE SET encrypted_value=excluded.encrypted_value,saved_at=excluded.saved_at", rusqlite::params![provider, encrypted, saved])
                    .map_err(|_| CredentialError::Unavailable("保存凭据失败，原值未改变".into()))?;
            }
        }
        transaction
            .commit()
            .map_err(|_| CredentialError::Unavailable("保存凭据失败，原值未改变".into()))
    }
}

impl CredentialBackend for SqliteCredentialBackend {
    fn save_jina(&self, value: Value, saved_at: f64) -> Result<(), CredentialError> {
        self.mutate_rows("jina", saved_at, |stored| Ok(Some(merge_jina_metadata(value, stored))))
    }
    fn read(&self, provider: &str) -> Result<Option<Vec<u8>>, CredentialError> {
        if self.path.as_os_str().is_empty() {
            return Err(CredentialError::Unavailable("无法定位配置数据库".into()));
        }
        if !self.path.exists() {
            return Ok(None);
        }
        let connection = self.connection()?;
        let encrypted: Option<Vec<u8>> = connection
            .query_row(
                "SELECT encrypted_value FROM credentials WHERE provider=?1",
                [provider],
                |r| r.get(0),
            )
            .optional()
            .map_err(|_| CredentialError::Unavailable("无法读取配置数据库凭据".into()))?;
        encrypted.map(|blob| crypt(&blob, false)).transpose()
    }
    fn write(&self, provider: &str, blob: &[u8]) -> Result<(), CredentialError> {
        require_storage()?; // Platform gate before any database access.
        let (_, saved_at) = decode_blob(provider, blob)?;
        let encrypted = crypt(blob, true)?; // Encryption must succeed before touching database.
        let mut connection = self.connection()?;
        let transaction = connection
            .transaction()
            .map_err(|_| CredentialError::Unavailable("配置数据库事务失败".into()))?;
        transaction.execute("INSERT INTO credentials(provider,encrypted_value,saved_at) VALUES(?1,?2,?3) ON CONFLICT(provider) DO UPDATE SET encrypted_value=excluded.encrypted_value,saved_at=excluded.saved_at", rusqlite::params![provider, encrypted, saved_at])
            .map_err(|_| CredentialError::Unavailable("保存凭据失败，原值未改变".into()))?;
        transaction
            .commit()
            .map_err(|_| CredentialError::Unavailable("保存凭据失败，原值未改变".into()))
    }
    fn delete(&self, provider: &str) -> Result<bool, CredentialError> {
        if self.path.as_os_str().is_empty() { return Err(CredentialError::Unavailable("无法定位配置数据库".into())); }
        if !self.path.exists() {
            return Ok(false);
        }
        self.connection()?
            .execute("DELETE FROM credentials WHERE provider=?1", [provider])
            .map(|n| n > 0)
            .map_err(|_| CredentialError::Unavailable("删除凭据失败".into()))
    }
    fn append(&self, provider: &str, keys: &[String], saved_at: f64) -> Result<(), CredentialError> {
        self.mutate_rows(provider, saved_at, |stored| append_rows(provider, stored, keys).map(Some))
    }
    fn remove_row(&self, provider: &str, index: usize, expected: &str, saved_at: f64) -> Result<(), CredentialError> {
        self.mutate_rows(provider, saved_at, |stored| {
            let stored = stored.ok_or(CredentialError::Invalid("credential rows changed; refresh and retry"))?;
            remove_row_at(provider, stored, index, expected)
        })
    }
}
// No optional entropy: protocol v1 interoperates with the Python CLI.
// DPAPI binds blobs to this Windows user, not against other same-user processes.
// Adding entropy requires a cross-language storage migration.
#[cfg(windows)]
pub(crate) fn crypt(bytes: &[u8], encrypt: bool) -> Result<Vec<u8>, CredentialError> {
    use windows_sys::Win32::{
        Foundation::{GetLastError, LocalFree, ERROR_INVALID_DATA, ERROR_INVALID_PARAMETER},
        Security::Cryptography::{
            CryptProtectData, CryptUnprotectData, CRYPTPROTECT_UI_FORBIDDEN, CRYPT_INTEGER_BLOB,
        },
    };
    if bytes.len() > u32::MAX as usize {
        return Err(CredentialError::Unreadable);
    }
    let input = CRYPT_INTEGER_BLOB {
        cbData: bytes.len() as u32,
        pbData: bytes.as_ptr() as *mut u8,
    };
    let mut output: CRYPT_INTEGER_BLOB = unsafe { std::mem::zeroed() };
    unsafe {
        let ok = if encrypt {
            CryptProtectData(
                &input,
                std::ptr::null(),
                std::ptr::null(),
                std::ptr::null_mut(),
                std::ptr::null(),
                CRYPTPROTECT_UI_FORBIDDEN,
                &mut output,
            )
        } else {
            CryptUnprotectData(
                &input,
                std::ptr::null_mut(),
                std::ptr::null(),
                std::ptr::null_mut(),
                std::ptr::null(),
                CRYPTPROTECT_UI_FORBIDDEN,
                &mut output,
            )
        };
        if ok == 0 {
            let code = GetLastError();
            // All API parameters are fixed here except the stored blob. A
            // truncated blob can produce INVALID_PARAMETER rather than INVALID_DATA.
            if !encrypt && matches!(code, ERROR_INVALID_DATA | ERROR_INVALID_PARAMETER) {
                return Err(CredentialError::DecryptionFailed(code));
            }
            return Err(CredentialError::Unavailable(format!(
                "DPAPI {}失败 (Windows error {})",
                if encrypt { "加密" } else { "解密" },
                code
            )));
        }
        let value = std::slice::from_raw_parts(output.pbData, output.cbData as usize).to_vec();
        LocalFree(output.pbData as *mut std::ffi::c_void);
        Ok(value)
    }
}
#[cfg(not(windows))]
pub(crate) fn crypt(_: &[u8], _: bool) -> Result<Vec<u8>, CredentialError> {
    Err(CredentialError::PlatformUnsupported)
}

/// Whether this build's SQLite credential backend can encrypt a write on the
/// current platform. DPAPI binds to the Windows user; on other platforms every
/// encrypted path is unavailable and there is no plaintext fallback. This is a
/// compile-time platform fact, shared by the status payload and the write
/// guards — never inferred from a browser string or a failed operation.
#[cfg_attr(not(feature = "test-fixtures"), allow(dead_code))]
pub(crate) fn storage_supported() -> bool {
    cfg!(windows)
}

/// Guard for every encrypted credential write. Sits before any database
/// connection or file access so a request that bypasses a disabled UI cannot
/// touch existing credentials, and the failure is a stable mappable reason
/// rather than a generic save error.
#[cfg_attr(not(feature = "test-fixtures"), allow(dead_code))]
pub(crate) fn require_storage() -> Result<(), CredentialError> {
    if storage_supported() {
        Ok(())
    } else {
        Err(CredentialError::PlatformUnsupported)
    }
}

#[derive(Clone, Debug, Serialize, PartialEq)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS))]
#[cfg_attr(feature = "ts", ts(export_to = "types.d.ts"))]
pub struct CredentialStatus {
    /// present | absent | unreadable | unavailable, or a new value added later; UI must fall back to a raw string.
    pub state: String,
    pub saved_at: Option<f64>,
    pub error: String,
}
pub(crate) fn status_of(result: Result<Option<(Value, f64)>, CredentialError>) -> CredentialStatus {
    match result {
        Ok(Some((_, saved_at))) => CredentialStatus {
            state: "present".into(),
            saved_at: Some(saved_at),
            error: String::new(),
        },
        Ok(None) => CredentialStatus {
            state: "absent".into(),
            saved_at: None,
            error: String::new(),
        },
        Err(error) => CredentialStatus {
            state: if matches!(error, CredentialError::Unreadable | CredentialError::DecryptionFailed(_)) {
                "unreadable"
            } else {
                "unavailable"
            }
            .into(),
            saved_at: None,
            error: error.to_string(),
        },
    }
}

#[cfg(all(test, windows))]
mod decryption_tests {
    use super::*;

    #[test]
    fn invalid_dpapi_payload_reports_unreadable_not_unknown_availability() {
        let error = crypt(b"not a DPAPI payload", false).unwrap_err();
        assert!(error.to_string().contains("DPAPI"));
        assert_eq!(status_of(Err(error.clone())).state, "unreadable", "{error:?}");
        assert_eq!(
            status_of(Err(CredentialError::Unavailable("database unavailable".into()))).state,
            "unavailable"
        );
    }
}
